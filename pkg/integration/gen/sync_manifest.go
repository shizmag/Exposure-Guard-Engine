package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
)

func main() {
	// Locate root tools.lock.json relative to this file
	// gen -> pkg/integration -> pkg -> root
	wd, err := os.Getwd()
	if err != nil {
		fmt.Fprintf(os.Stderr, "failed to get working directory: %v\n", err)
		os.Exit(1)
	}

	// Try relative candidates to find root tools.lock.json
	candidates := []string{
		filepath.Join(wd, "tools.lock.json"),
		filepath.Join(wd, "..", "..", "tools.lock.json"),
		filepath.Join(wd, "..", "tools.lock.json"),
	}

	var rootManifest string
	for _, c := range candidates {
		if fi, err := os.Stat(c); err == nil && !fi.IsDir() {
			rootManifest = c
			break
		}
	}

	if rootManifest == "" {
		fmt.Fprintf(os.Stderr, "cannot find root tools.lock.json from %s\n", wd)
		os.Exit(1)
	}

	data, err := os.ReadFile(rootManifest)
	if err != nil {
		fmt.Fprintf(os.Stderr, "failed to read %s: %v\n", rootManifest, err)
		os.Exit(1)
	}

	outPath := filepath.Join(filepath.Dir(rootManifest), "pkg", "integration", "tools_lock_gen.go")

	code := fmt.Sprintf(`// Code generated by pkg/integration/gen/sync_manifest.go from canonical /tools.lock.json. DO NOT EDIT.

package integration

var embeddedToolsLock = []byte(%s)
`, strconv.Quote(string(data)))

	if err := os.WriteFile(outPath, []byte(code), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "failed to write %s: %v\n", outPath, err)
		os.Exit(1)
	}

	fmt.Printf("Successfully generated %s from %s (%d bytes)\n", outPath, rootManifest, len(data))
}
